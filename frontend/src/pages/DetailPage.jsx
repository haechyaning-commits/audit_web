const PIPE_CELL_RE = /\s\|\s/g;
function looksLikePipeTable(text) {
  const matches = text.match(PIPE_CELL_RE);
  return Boolean(matches && matches.length >= 2);
}

// 2026-08-24: "table" 블록이 전부 파이프 그리드는 아님(캡션 뒤에 붙는 표/그림
// 조각, looksLikeFlattenedTable의 불릿 반복 문단도 같은 "table" 타입으로 옴) —
// 그런 것들은 셀 경계가 없어서 실제 열로 못 나눔. 그래서 렌더링 시점에 "이 텍스트가
// 행마다 같은 개수로 ' | ' 나뉘는 깔끔한 그리드인가"를 별도로 확인해서, 맞을 때만
// 진짜 `<table>`로 그리고(모노스페이스 텍스트보다 훨씬 읽기 쉬움), 아니면 기존처럼
// 원문 그대로 보여줌(안전장치 — 셀 개수 안 맞는 행 하나라도 있으면 통째로 포기).
function parsePipeTableRows(text) {
  const lines = text.split("\n").filter((l) => l.trim());
  if (lines.length === 0) return null;
  const rows = lines.map((l) => l.split(/\s*\|\s*/).map((c) => c.trim()));
  const colCount = rows[0].length;
  if (colCount < 2) return null; // 열이 1개뿐이면 표 그리드가 아님
  if (!rows.every((r) => r.length === colCount)) return null;
  return rows;
}

/** 원문을 문단 단위 블록으로 나눔(렌더링 전 순수 데이터 단계) — renderRawText와
 * buildToc가 같은 블록 목록을 같이 써서 목차 항목과 실제 앵커가 항상 일치하게 함
 * (law.go.kr류 조문 목차 참고 요청, 2026-08-12).
 *
 * 원문의 줄바꿈(\n)은 대부분 PDF가 페이지 폭에 맞춰 끊은 자리라 실제 문장/문단 구분과
 * 다름(심하면 "근무하" / "고 있는" 처럼 단어 중간에서도 끊김) — 그 줄을 그대로 각자 블록
 * 으로 렌더링하면 원래 한 문장이 짧은 조각으로 뚝뚝 끊겨 보임(2026-08-12 피드백).
 * 그래서 헤딩/불릿 줄이나 빈 줄(진짜 문단 구분)을 만나기 전까지 이어지는 일반 줄들은
 * 공백으로 합쳐서 하나의 문단으로 흘러가게 함. */
function splitIntoBlocks(text) {
  // 문서 전체에서 "숫자)" 형태로 붙어 나온 각주 참조 번호를 미리 수집(각주 판별용,
  // FOOTNOTE_REF_RE 주석 참고).
  const footnoteNums = new Set();
  for (const m of text.matchAll(FOOTNOTE_REF_RE)) {
    footnoteNums.add(m[1]);
  }

  const blocks = [];
  let para = [];
  let paraType = "body";
  let nextIsTable = false; // 표/그림 캡션 바로 다음 문단인지
  // 직전에 flush된 블록의 타입 — 각주 판별에 씀(아래 각주 분기 참고). 목록 헤딩은
  // 항상 그 앞이 "heading"/"bullet"(다른 항목의 헤딩/본문)이고, 각주는 페이지 하단에
  // 있던 게 그대로 이어붙은 거라 항상 그 앞이 미완성 "body" 문단(또는 바로 위 각주)임.
  let prevType = null;
  // 2026-08-18: 가장 최근에 본 "N) ..." 목록 헤딩의 번호 — 아래 각주 분기에서 씀.
  // "1) 법령... (본문 설명 문단) 2) 법령..."처럼 번호 목록 항목마다 설명 문단이 붙는
  // 문서는, 다음 항목("2)")이 항상 헤딩/불릿 바로 다음이 아니라 body 문단 바로 다음에
  // 옴 — 각주 판별 조건 ②("직전이 body/footnote")를 만족해버려서 실제로는 목록 항목인데
  // 각주로 오분류되는 문제를 실제 스크린샷으로 확인함(한국가스공사 2021 사례). 직전
  // 목록 번호 + 1과 정확히 같으면 목록 연속으로 보고 각주 판정에서 제외.
  let lastHeadingListNum = null;
  // 2026-08-18: "□" 기호 혼자만 있는 줄 바로 다음 줄에 "점검 개요" 같은 실제 소제목
  // 텍스트가 오는 문서를 실제로 확인함(한국임업진흥원 2026 — 원래 "□ 점검 개요"가 PDF
  // 줄바꿈으로 기호와 글자가 갈라진 것으로 보임). "□" 혼자인 줄은 뒤에 오는 non-space
  // 글자가 없어서 BULLET_RE에 안 걸려 그냥 body로 흘러들어가고, 그 다음 줄도 별道
  // 패턴이 없으면 body라 앞 문단(심하면 제목 문단)에 그대로 흡수되던 문제("본문 중간에
  // 안 어울리는 게 낀다"/"제목이 눈에 안 띈다"류 피드백과 같은 원인 계열) — 기호 단독
  // 줄을 바로 blocks에 넣지 않고 보류해뒀다가, 바로 다음 줄과 합쳐서 하나의 줄처럼
  // 분류함("□ 점검 개요"로 합쳐지면 이후 로직 변경 없이도 자연스럽게 처리됨).
  let pendingGlyph = null;
  // 2026-08-20: "붙임" 라벨 바로 뒤 첨부목록 문단을 누적하는 중인지 — splitAttachmentLabel
  // 주석 참고. 이 문단이 계속 이어지는 동안(flushPara로 안 끊기는 동안)만 true로 유지되고,
  // 어떤 이유로든 문단이 끊기면(빈 줄/다른 헤딩·불릿·필드·캡션 등) flushPara()에서
  // 자동으로 false가 되므로 "같은 문단이 이어지는 동안만" 정확히 유지됨.
  let inAttachmentList = false;

  function flushPara() {
    inAttachmentList = false;
    if (para.length === 0) return;
    // 2026-08-18: 표/그림 조각 블록("table" 타입)은 다른 문단(body/bullet 등)과 달리
    // PDF 줄바꿈이 "문장이 길어서 끊긴 자리"가 아니라 "표의 서로 다른 셀/행"일 가능성이
    // 높음 — 실제 문서(한국토지주택공사 "시간외근무 부적절" [표 1])로 확인. 지금까지
    // 다른 문단처럼 공백으로 다 이어붙여서 완전히 뜻 없는 단어 나열이 됐었는데, 줄바꿈을
    // 그대로 살리면 최소한 원래 줄 단위 구분은 남길 수 있음 — CSS(`raw-line-table > div`)
    // 는 이미 white-space: pre-wrap이라 애초에 줄바꿈을 살릴 걸 전제로 하고 있었음(JS가
    // 안 살리고 있었던 게 이 둘 사이 드리프트였음).
    // 2026-08-21: "[표 N]" 캡션이 없어서 bullet로 흘러들어온 문단이 사실 표
    // 데이터였던 경우(looksLikeFlattenedTable 주석 참고) — flush 시점에 재분류해서
    // table과 똑같이 줄바꿈 보존 + 접이식(<details>) 처리되게 함.
    // 2026-08-24: 문서 맨 첫 블록이 표지(looksLikeCoverBlock 참고)면 "cover" 타입으로
    // 재분류 — table과 마찬가지로 줄바꿈을 보존해서 뱃지/제목/날짜/기관명이 원본처럼
    // 각자 줄로 보이게 함(CSS는 raw-line-cover, renderRawText는 일반 분기 그대로 재사용).
    // 2026-08-24: HWP 표 손실 복구가 되살린 "셀 | 셀" 형태(looksLikePipeTable 참고)도
    // table로 재분류 — 캡션("[표 N]") 없이 body/bullet 어느 쪽으로 흘러들어왔든 상관없이
    // 이 신호만으로 판정(파이프 문자는 이 말뭉치 산문에 정상적으로 나올 일이 없어 안전).
    const isLeadingCover =
      blocks.length === 0 && paraType === "body" && looksLikeCoverBlock(para);
    const paraJoined = para.join(" ");
    const type =
      (paraType === "bullet" && looksLikeFlattenedTable(paraJoined)) ||
      looksLikePipeTable(paraJoined)
        ? "table"
        : isLeadingCover
          ? "cover"
          : paraType;
    const text = type === "table" || type === "cover" ? para.join("\n") : paraJoined;
    blocks.push({ type, text });
    prevType = type;
    para = [];
    paraType = "body";
  }

  for (const rawLine of text.split("\n")) {
    let trimmed = rawLine.trim();

    if (!trimmed || ORNAMENT_GLYPH_LINE_RE.test(trimmed)) {
      // 다음 줄과 못 합쳐진 채 문단이 끊기는 경우 — 기호를 그냥 잃어버리지 않고
      // 독립된 조각으로라도 살려둠(원문 그대로 다 보여준다는 기존 방침 유지).
      if (pendingGlyph) {
        para.push(pendingGlyph);
        pendingGlyph = null;
      }
      flushPara();
      continue;
    }

    if (LONE_BULLET_GLYPH_RE.test(trimmed)) {
      pendingGlyph = trimmed;
      continue;
    }
    if (pendingGlyph) {
      trimmed = `${pendingGlyph} ${trimmed}`;
      pendingGlyph = null;
    }

    // 2026-08-14: 각주 판별 — classifyLine의 일반 "숫자) 내용" 헤딩 패턴보다 먼저
    // 검사해야 함. 두 조건을 동시에 요구해서 오탐을 좁힘: ①이 번호가 본문 어딘가에
    // 참조로 붙어 나온 적이 있고, ②바로 앞이 아직 안 끝난 본문 문단(또는 바로 위
    // 각주)일 것 — 진짜 목록 헤딩("1) 태양광...")은 항상 상위 헤딩/불릿 블록 바로
    // 다음에 오므로 ②를 만족하지 않아 여기 안 걸림(실제 문서로 확인).
    // "바로 앞"은 아직 flush 안 되고 누적 중인 para가 있으면 그 para의 타입(paraType),
    // 없으면 마지막으로 flush된 블록의 타입(prevType)임 — para가 비어있지 않을 때도
    // prevType만 보면 그 이전(이미 flush된) 블록 타입을 잘못 참조하게 됨.
    const effectivePrevType = para.length > 0 ? paraType : prevType;
    const footnoteMatch = FOOTNOTE_DEF_RE.exec(trimmed);
    const continuesHeadingList =
      lastHeadingListNum !== null &&
      Number(footnoteMatch?.[1]) === lastHeadingListNum + 1;
    // 2026-08-20: 실제 문서(한국자산관리공사 2021, 9ddc6393057cc532)를 디버그
    // 추적해서 확인함 — "* 당시 관련자는..." 같은 "*" 불릿이 각주 정의 줄보다
    // 먼저 나와서 그 뒤 평문들을 계속 "bullet" 문단으로 흡수하다가 진짜 각주
    // 정의 줄까지 삼켜버리는 경우(effectivePrevType==="bullet"), 그리고 "[표 1]"
    // 캡션 뒤 표 데이터를 흡수하는 중에 각주 정의 줄이 나오는 경우
    // (effectivePrevType==="table")에는 각주 판별 조건에서 막혀서 각주가 아예
    // 인식이 안 되고 있었음. SOURCE_NOTE_RE("자료:"/"출처:")가 표 블록을 강제로
    // 끝내는 경계로 이미 쓰이는 것과 같은 이유로, 진짜 각주 정의 줄(번호가
    // footnoteNums에 있음)도 불릿/표 문단을 끝내는 경계로 인정함.
    //
    // 2026-08-21(각주 15/16, 8/20에 특정한 원인 기반): 같은 문서에서 "15) 과잉금지의 원칙..."처럼
    // 각주 본문 자체가 24자 이하로 짧으면, 바로 위 classifyLine의 "짧은 번호
    // 헤딩" 규칙에 걸려 이 줄이 heading으로 잘못 승격됨 — 그 heading push
    // 직후엔 para가 비어서 effectivePrevType이 "heading"이 되는데, 이게 허용
    // 목록에 없어서 정작 진짜 각주였던 이 줄 자신이 각주로 인식조차 안 되고
    // heading으로 새어버렸던 것(그 뒤에 이어지는 각주도 직전이 "heading"이라
    // 같은 이유로 연쇄로 계속 heading이 됨). 재현: 실제 heading 줄 바로 다음에
    // 짧은 각주 정의가 오는 최소 케이스로 확인(아래 자가 검증 참고). bullet/
    // table을 인정한 것과 같은 이유로 heading 직후도 진짜 각주 정의 줄(번호가
    // footnoteNums에 있음, continuesHeadingList로 목록 연속은 여전히 걸러짐)이면
    // 인정함 — 일단 첫 각주 한 줄만 정상 인식되면 그 다음부터는 paraType이
    // "footnote"로 유지되므로 연쇄 자체가 더 이상 안 생김.
    //
    // 2026-08-21(신호② 표본 5건 실 DB 디버그로 확인): "자료: ○○ 제출자료
    // 재구성"(caption) 바로 다음, 또는 "관계부서 의견"류 필드(field) 바로
    // 다음에 각주 정의 줄이 곧장 이어지는 문서가 실제로 다수 있었음(한국가스공사
    // 2025 등 5건 전부 이 패턴). caption/field 둘 다 effectivePrevType 허용
    // 목록에 없어서 정작 각주 자신이 인식 안 되고 heading으로 샜고, 그 결과
    // lastHeadingListNum이 오염돼 다음 각주 번호까지 continuesHeadingList에
    // 걸려 연쇄로 실패함(한국농어촌공사 2024, a728ba6793fbd689에서 각주
    // 1·2 둘 다 이 경로로 실패하는 것 확인). bullet/table/heading을 인정한
    // 것과 같은 이유로 caption/field 직후도 인정함.
    //
    // 2026-08-20(별도 세션, webpage-data-verification-w7o0qj 병합, 각주 15/16의
    // "진짜" 근본 원인): 한국자산관리공사 2019(65fc6662db4c8570)를 조사하다가 —
    // 위 heading 허용이 없던 시점에도, "(징계)" 같은 괄호 라벨(PAREN_LABEL_RE)
    // 헤딩 바로 다음에 오는 각주만 별도로 허용하면 15/16이 풀렸다는 걸 발견함.
    // 더 깊이 파보니 실제 트리거는 따로 있었음 — 각주 14 문단 안에 인용된
    // "5. 공사의 여러 규정, 서약사항 및 지시명령을 위반하여"(마침표 나열식 목록,
    // 법령인용 힌트 없음)가 classifyLine의 "80자 이내+문장종결없음" 헤딩 예외에
    // 걸려서 각주 14 문단을 중간에 끊어버렸던 것 — 아래 LAW_CITATION_HINT_RE로
    // 그 예외를 좁혀서 근본 해결(각주 14가 안 끊기니 15/16도 연쇄 없이 정상
    // 인식). 즉 위 heading 허용은 이 특정 문서의 증상을 우회하는 데는 이미
    // 충분했지만, LAW_CITATION_HINT_RE 쪽이 더 근본적인 수정이자 이 문서 밖의
    // 다른 나열식 목록 오탐(각주와 무관하게 헤딩으로 잘못 굵어지는 문제)까지
    // 같이 고침 — 둘 다 유지(위 heading 허용은 범용 안전망으로, 좁은
    // prevHeadingIsParenLabel 전용 분기는 위 heading 허용의 부분집합이라 병합 시 생략).
    if (
      footnoteMatch &&
      footnoteNums.has(footnoteMatch[1]) &&
      (effectivePrevType === "body" ||
        effectivePrevType === "footnote" ||
        effectivePrevType === "bullet" ||
        effectivePrevType === "table" ||
        effectivePrevType === "heading" ||
        effectivePrevType === "caption" ||
        effectivePrevType === "field") &&
      !continuesHeadingList
    ) {
      // 2026-08-19: 예전엔 이 줄 하나만 blocks에 바로 push해서, PDF 페이지폭 때문에
      // 각주 내용이 다음 줄로 넘어간 경우(실제 문서로 확인, "18)「감사규정」..." 다음
      // 줄에 "4. 주의 : ...") 그 이어지는 줄이 각주 판별에 안 걸려서 별도의 "body"
      // 문단으로 새어나가고 있었음(사용자 제보: "다 작은글씨인데 왜 한 줄만 적용
      // 되는지"). bullet/table과 같은 방식(paraType만 바꾸고 para에 누적)으로 고쳐서,
      // 다음 각주 번호나 헤딩/불릿을 만나기 전까지 이어지는 줄들이 같은 각주 문단으로
      // 계속 흡수되게 함 — effectivePrevType이 "footnote"로 유지되므로 새 각주 번호가
      // 나오면 정상적으로 끊기고 다음 각주로 넘어감(위 실제 문서로 검증).
      flushPara();
      paraType = "footnote";
      para.push(trimmed);
      continue;
    }

    const kind = classifyLine(trimmed);

    // 2026-08-14: 표 데이터를 접어서 보여주는 중(paraType === "table")에 표 안 날짜
    // 셀 하나만 있는 줄("(2025. 8. 8.)")이 우연히 PAREN_LABEL_RE(괄호 라벨 헤딩)에도
    // 걸려서, 매 셀마다 표가 끊기고 남은 행은 표가 아닌 통짜 본문으로 새어나가던 문제를
    // 실제 문서("[공직기강 점검 2회 적발자 현황]" 표)로 확인함 — 표를 누적하는 중에
    // 나온 괄호 라벨 줄은 진짜 새 소제목이 아니라 표 셀 조각으로 보고 표 문단에
    // 그대로 흡수시킴(접힌 박스가 끊기지 않고 표 데이터 전체를 담게 됨).
    if (kind === "heading" && paraType === "table" && PAREN_LABEL_RE.test(trimmed)) {
      para.push(trimmed);
      continue;
    }
    // 2026-08-20: 각주 15/16 미인식 버그(STATUS.md에서 "다음 세션에서 이어서 진단"으로
    // 미뤄뒀던 것) — 실제 문서(한국자산관리공사 2021, 9ddc6393057cc532)를 다시 추적해서
    // 진짜 원인을 찾음. 각주 정의문이 "「인사규정」제44조(징계대상)\n5. 공사의 여러
    // 규정, 서약사항 및 지시명령을 위반하여 공사 내의 질서를 문란케 한 직원"처럼 법조항
    // 자체를 그대로 인용하면서 다음 줄이 "5. ..."로 시작하는 경우, 이 줄은 각주 14의
    // 이어지는 설명일 뿐인데 isGenericListHeading(번호 헤딩 휴리스틱, 80자 이하+문장종결
    // 없음)에 걸려 heading으로 잘못 승격됨 — 그 순간 flushPara()로 각주 14 문단이
    // 끊기고 prevType이 "heading"이 되어, 바로 다음에 오는 진짜 각주 15/16이
    // effectivePrevType 허용 목록(body/footnote/bullet/table)에 "heading"이 없어서
    // 아예 각주로 인식되지 못하는 연쇄로 이어짐. 위 표 흡수(PAREN_LABEL_RE)와 같은
    // 이유로, 각주 문단을 누적하는 중(paraType === "footnote")에 나온 번호/가나다 헤딩
    // 휴리스틱 매칭 줄은 진짜 새 소제목이 아니라 각주가 인용한 법조항 번호일 가능성이
    // 높다고 보고 그대로 흡수시킴 — 실제 문서로 검증: footnote 블록 17개 → 19개(15,16
    // 정상 인식). splitLawCitationHeading으로 분리되는 진짜 법령인용 헤딩(라벨/인용문
    // 분리)은 이 흡수에서 제외 — 그 경우는 여전히 명확한 구조 신호라 헤딩으로 분리하는
    // 게 맞음.
    if (
      kind === "heading" &&
      paraType === "footnote" &&
      isGenericListHeading(trimmed) &&
      !splitLawCitationHeading(trimmed)
    ) {
      para.push(trimmed);
      continue;
    }
    // 2026-08-20: "붙임" 첨부목록 문단을 누적하는 중(inAttachmentList)에 나온 번호
    // 헤딩 휴리스틱 매칭 줄("2. 당시...")은 새 목록 항목(원래 첨부 캡션 나열이지 새
    // 섹션 헤딩이 아님)일 뿐인데 heading으로 잘못 승격되던 문제 — splitAttachmentLabel
    // 주석 참고. 위 각주 흡수와 같은 패턴으로 heading 승격을 막고 그대로 흡수시킴.
    if (
      kind === "heading" &&
      inAttachmentList &&
      isGenericListHeading(trimmed) &&
      !splitLawCitationHeading(trimmed)
    ) {
      para.push(trimmed);
      continue;
    }
    if (kind === "heading") {
      flushPara();
      // 2026-08-18: "1) 법령 「...」 제N조(...) '인용문..." 처럼 번호 라벨 뒤에 줄바꿈
      // 없이 인용문이 바로 붙은 경우, 라벨까지만 헤딩으로 두고 인용문은 새 본문 문단으로
      // 흘려보냄(splitLawCitationHeading 주석 참고) — 실제 스크린샷으로 확인된 과굵게 버그 수정.
      const citationSplit = splitLawCitationHeading(trimmed);
      if (citationSplit) {
        const [label, body] = citationSplit;
        // 법령인용 라벨은 TITLE_RE("제목" 라벨)에 걸릴 일이 없지만, 아래 일반
        // heading push와 마찬가지로 isTitle을 명시적으로 계산해둬서 undefined로
        // 새지 않게 함(fixMissingTitleNumber의 b.isTitle 체크와 일관성 유지).
        blocks.push({ type: "heading", text: label, isTitle: TITLE_RE.test(label) });
        prevType = "heading";
        lastHeadingListNum = extractListNum(label);
        nextIsTable = false;
        paraType = "body";
        para.push(body);
        continue;
      }
      // 2026-08-20: "[통보] ○○팀장은..." 류(BRACKET_LABEL_WITH_TRAILING_RE) 라벨도
      // 위 법령인용 라벨과 똑같은 문제(줄 전체가 통째로 볼드돼 다음 줄과 뒤죽박죽)라
      // 같은 방식으로 라벨/내용 분리(splitBracketLabelHeading 주석 참고).
      const bracketSplit = splitBracketLabelHeading(trimmed);
      if (bracketSplit) {
        const [label, body] = bracketSplit;
        blocks.push({ type: "heading", text: label, isTitle: false });
        prevType = "heading";
        lastHeadingListNum = extractListNum(label); // 항상 null(라벨이 "N)"로 안 시작함)
        nextIsTable = false;
        paraType = "body";
        para.push(body);
        continue;
      }
      // 2026-08-20: "붙임 : 1. ..." 라벨도 같은 이유로 라벨/내용 분리(splitAttachmentLabel
      // 주석 참고) — 뒤이은 번호 항목들은 위 inAttachmentList 흡수 분기가 계속 처리.
      const attachmentSplit = splitAttachmentLabel(trimmed);
      if (attachmentSplit) {
        const [label, body] = attachmentSplit;
        blocks.push({ type: "heading", text: label, isTitle: false });
        prevType = "heading";
        lastHeadingListNum = null;
        nextIsTable = false;
        paraType = "body";
        if (body) para.push(body);
        inAttachmentList = true;
        continue;
      }
      // isTitle은 여기(원본 trimmed 기준)서 한 번만 계산해 저장 — 아래
      // fixMissingTitleNumber가 표시용 text에 "1. "을 덧붙여도 TITLE_RE 재검사에
      // 걸리지 않게(제목 스타일/목차 제외가 계속 정확히 동작하게) 하기 위함.
      blocks.push({ type: "heading", text: trimmed, isTitle: TITLE_RE.test(trimmed) });
      prevType = "heading";
      lastHeadingListNum = extractListNum(trimmed);
      nextIsTable = TABLE_CAPTION_RE.test(trimmed);
      continue;
    }
    if (kind === "field") {
      flushPara();
      const field = matchFieldLabel(trimmed);
      blocks.push({ type: "field", label: field.label, value: field.value });
      prevType = "field";
      nextIsTable = false;
      continue;
    }
    if (kind === "caption") {
      flushPara(); // 표 블록이 진행 중이었으면 여기서 확실히 끝냄(6차 수정 이유 참고)
      blocks.push({ type: "caption", text: trimmed });
      prevType = "caption";
      nextIsTable = false;
      continue;
    }
    // 2026-08-19: 각주를 누적하는 중(paraType === "footnote")에 나온 불릿 줄은 새
    // 항목이 아니라 그 각주의 하위 설명으로 봄(실제 문서로 확인 — "1) 직장 내
    // 괴롭힘 : 고용노동부 예방·대응 매뉴얼(2023.4)" 바로 다음 줄이 "- 행위요건 : ..."
    // 로 그 각주를 부연하는데, 예전엔 불릿을 만나는 즉시 무조건 새 문단으로 끊어서
    // paraType이 "footnote"에서 "bullet"로 바뀌어버림 — 그러면 바로 이어지는 각주
    // 2)/3)/4)번이 effectivePrevType 조건("body"|"footnote")을 못 만족해서 각주로
    // 인식이 안 되고 그 불릿 문단에 통째로 흡수돼 버렸음(한국부동산원 2024,
    // 4df12939e14a66c3로 확인). 각주 문단 안에서는 흡수시켜서 paraType을
    // "footnote"로 유지 — 뒤이은 각주 번호가 계속 정상 인식되게 함.
    if (kind === "bullet" && paraType === "footnote") {
      para.push(normalizeGlyphBullet(trimmed));
      continue;
    }
    if (kind === "bullet") {
      flushPara(); // 불릿은 새 항목 시작 — 앞 문단과 분리(표 캡션 뒤라도 여기서 끊음)
      paraType = "bullet";
      nextIsTable = false;
      para.push(normalizeGlyphBullet(trimmed));
      continue;
    }
    if (para.length === 0 && nextIsTable) {
      paraType = "table";
      nextIsTable = false;
    }
    para.push(trimmed);
  }
  if (pendingGlyph) para.push(pendingGlyph); // 문서가 기호 단독 줄로 끝나는 경우
  flushPara();
  // 제목 줄 번호("1. ") 보정 — isTitle 플래그를 이미 저장해뒀으므로 아래에서 text를
  // 바꿔도 스타일/목차 판별에는 영향 없음(위 fixMissingTitleNumber 주석 참고).
  fixMissingTitleNumber(blocks);
  // 위 분류 로직(각주/헤딩/표 판별 등)은 전부 원본 "[부서]" 문자열 기준으로 이미
  // 끝난 뒤이므로, 화면에 보여줄 텍스트에만 마지막에 치환을 적용함 — classifyLine
  // 등이 "[부서]"를 헤딩으로 오인하지 않게 설계된 기존 로직(6차 수정)과 안 얽히게 함.
  // "field" 블록은 text가 아니라 label/value로 나뉘어 있어서 둘 다 따로 치환.
  return blocks.map((b) =>
    b.type === "field"
      ? { ...b, label: maskDeptPlaceholder(b.label), value: maskDeptPlaceholder(b.value) }
      : { ...b, text: maskDeptPlaceholder(b.text) },
  );
}

/** 헤딩 블록에만 앵커 id를 붙여서 렌더링 — 목차(TocSidebar)가 이 id로 점프함.
 * id는 등장 순서 기반("heading-3")으로만 부여, buildToc와 항상 같은 순서/조건이어야 함.
 * 제목 줄(TITLE_RE)은 별도 "title" 타입으로 렌더링 — 다른 헤딩보다 크게, 세리프로. */
function renderRawText(blocks, query) {
  let headingIdx = 0;
  return blocks.map((b, i) => {
    if (b.type === "table") {
      const rows = parsePipeTableRows(b.text);
      return (
        <details key={i} className="raw-line-table">
          <summary>표/그림 데이터 (펼쳐보기)</summary>
          {rows ? (
            <table className="raw-table-grid">
              <tbody>
                {rows.map((cells, ri) => (
                  <tr key={ri} className={ri === 0 ? "raw-table-header-row" : undefined}>
                    {cells.map((cell, ci) => (
                      <td key={ci}>{query ? highlightMatches(cell, query) : cell}</td>
                    ))}
                  </tr>
                ))}
              </tbody>
            </table>
          ) : (
            <div>{query ? highlightMatches(b.text, query) : b.text}</div>
          )}
        </details>
      );
    }
    if (b.type === "field") {
      // 2026-08-18: 소관부서/조치부서/관련자 등 "라벨 + 값" 필드 — 라벨만 굵게, 값은
      // 보통 굵기로 나란히(원본 PDF와 같은 대비, matchFieldLabel 주석 참고). 값에서만
      // 검색어 하이라이트 적용(라벨은 "소관부서" 같은 고정 문구라 검색어와 겹칠 일이 거의 없음).
      return (
        <div key={i} className="raw-line raw-line-field">
          <b className="raw-line-field-label">{b.label}</b>
          <span className="raw-line-field-value">
            {query ? highlightMatches(b.value, query) : b.value}
          </span>
        </div>
      );
    }
    if (b.type !== "heading") {
      return (
        <div key={i} className={`raw-line raw-line-${b.type}`}>
          {query ? highlightMatches(b.text, query) : b.text}
        </div>
      );
    }
    const isTitle = b.isTitle;
    const id = `heading-${headingIdx++}`;
    return (
      <div
        key={i}
        id={id}
        className={`raw-line ${isTitle ? "raw-line-title" : "raw-line-heading"}`}
      >
        {query ? highlightMatches(b.text, query) : b.text}
      </div>
    );
  });
}

/** 목차 항목만 뽑음 — renderRawText의 id 채번 방식과 반드시 같은 순서/조건("heading"
 * 블록만, 등장 순서대로 — 제목도 포함해서 카운트)이어야 앵커가 안 어긋남. 다만 목차
 * 화면에는 제목 자체는 안 보여줌(페이지에 이미 큼직하게 있어서 중복). */
function buildToc(blocks) {
  let headingIdx = 0;
  const items = [];
  for (const b of blocks) {
    if (b.type !== "heading") continue;
    const id = `heading-${headingIdx++}`;
    if (b.isTitle) continue;
    items.push({ id, text: b.text });
  }
  return items;
}

function TocSidebar({ items }) {
  if (items.length < 3) return null; // 항목 적으면 스크롤 한 번이면 끝 — 목차가 노이즈만 됨

  function handleClick(e, id) {
    e.preventDefault();
    document
      .getElementById(id)
      ?.scrollIntoView({ behavior: "smooth", block: "start" });
  }

  return (
    <nav className="toc-sidebar" aria-label="원문 목차">
      <p className="toc-label">목차</p>
      <ol>
        {items.map((item) => (
          <li key={item.id}>
            <a href={`#${item.id}`} onClick={(e) => handleClick(e, item.id)}>
              {item.text}
            </a>
          </li>
        ))}
      </ol>
    </nav>
  );
}

