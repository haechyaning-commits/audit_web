// 필수(\s+)로 요구하던 탓에 이 각주가 아예 인식조차 안 되고 직전 문단에 흡수돼
// 버렸음. \s*로 완화(공백 0개 이상) — footnoteNums 사전 스캔 + splitIntoBlocks의
