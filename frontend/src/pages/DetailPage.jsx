const FOOTNOTE_DEF_RE = /^(\d{1,2})\)\s*\S/;
// 목록 헤딩 줄("1) 법령 ...")의 맨 앞 번호만 뽑음 — 아래 두 가지에 씀: ①연속된 번호
// 목록인지 판단(각주 오판별 방지, splitIntoBlocks 참고) ②splitLawCitationHeading으로
// 라벨만 잘라낸 뒤에도 그 라벨 자체의 번호를 계속 추적하기 위함.
//
// 2026-08-20: 원래 "[.)]"로 마침표/괄호 둘 다 받았는데, 이 번호가 ①에서 각주
// 오판별 방지용 lastHeadingListNum으로 쓰이면서 실제 문서(한국조폐공사 2016,
// f35fdc468543c358)로 확인된 버그가 있었음 — "1. 업무개요 / 2. 관계규정..."
// 처럼 마침표로 된 최상위 문서 섹션 번호(사실상 모든 감사보고서에 있는 흔한
// 구조)까지 이 카운터를 오염시켜서, 그 뒤에 나오는 진짜 각주("1)"/"2)")가
// "목록 연속"으로 오판별돼 아예 각주로 인식이 안 되는 문제였음(한국자산관리공사
// 2021, 9ddc6393057cc532에서도 재현). 실제 "N) 법령 「...」..." 인용 목록은
// 지금까지 확인된 사례 전부 괄호(")")만 썼지 마침표를 쓴 적이 없어서, 괄호만
// 받게 좁힘 — 마침표로 된 최상위 섹션 번호는 이제 이 카운터에 안 걸림.
const LIST_HEADING_NUM_RE = /^(\d{1,2})\)\s+\S/;
function extractListNum(text) {
  const m = LIST_HEADING_NUM_RE.exec(text);
  return m ? Number(m[1]) : null;
}

// 2026-08-18: "1) 법령 「공직자 윤리법」 제3조의 2. 제2항(공기업) '공직유관단체인 우리
// 공사는..." — 사용자가 원본 PDF ↔ 웹페이지 스크린샷으로 제보: 원본은 번호+법령 인용
// (조/항 번호까지)만 굵고 그 뒤 실제 인용문(따옴표로 시작)은 안 굵은 별도 문단인데,
// 텍스트 추출 시 둘 사이에 줄바꿈이 없어서 한 줄로 붙어버림 — 위 번호 헤딩 패턴이 줄
// 전체를 헤딩(굵게)으로 삼켜서 인용문까지 통째로 굵게 나오는 문제였음.
// 실제 raw_text(한국가스공사 2021, `7a766550f0f873b7`)로 검증해보니 "괄호 바로 뒤에
// 공백+따옴표"로는 못 잡는 경우가 있었음 — "제7조(성실의무) 제1항‘직원은..."처럼 괄호
// 뒤에 조/항 번호가 공백 없이 하나 더 붙고 나서야 따옴표가 오는 문서도 실제로 있었음
// (사용자가 "2) 공사 취업규칙도 마찬가지"라고 후속 제보). 그래서 "괄호 바로 뒤"가 아니라
// "줄 안에서 처음 나오는 인용부호 앞에 닫는 괄호가 하나라도 있었는지"로 조건을 넓힘 —
// 법령명을 감싸는 「」/｢｣는 인용부호 집합에 안 들어있어서 오탐 안 함(splitLawCitationHeading
// 참고). 인용부호가 줄 맨 앞에 가깝게(괄호가 나오기도 전에) 나오면 애초에 조건 ②
// (괄호 있어야 함)에서 걸러짐.
const QUOTE_CHAR_RE = /[‘’“”'"]/;

/** 번호목록 헤딩 줄에서 "법령/조항 인용 라벨 + 그 뒤에 줄바꿈 없이 붙은 인용문" 경계를
 * 찾아 [라벨, 인용문]으로 나눔. 조건을 만족 못 하면 null(분리 안 함, 줄 전체를 그대로
 * 헤딩으로 둠) — 인용부호가 없거나, 있어도 그 앞에 괄호로 끝나는 조/항 인용이 전혀
 * 없으면(예: 관련자 진술처럼 그냥 문장 중간의 따옴표) 라벨 형태가 아니라고 보고 스킵. */
function splitLawCitationHeading(trimmed) {
  if (!LIST_HEADING_NUM_RE.test(trimmed)) return null;
  const quoteIdx = trimmed.search(QUOTE_CHAR_RE);
  if (quoteIdx <= 0) return null;
  const before = trimmed.slice(0, quoteIdx);
  // 2026-08-20: "7) 2021. 1. 30. 모바일 익명 커뮤니티 앱인 '블라인드'의..."처럼
  // 각주 정의 줄 자체가 우연히 비공식 인용부호(속어/앱 이름 등)를 포함하면,
  // 번호 접두어 자체의 괄호("7)"의 ")")까지 "조/항 인용 괄호"로 오인해서 각주가
  // 헤딩으로 잘못 쪼개지는 버그를 실제 문서(한국자산관리공사 2021,
  // 9ddc6393057cc532)로 확인함 — 번호 접두어는 제외하고 그 "뒤"에 별도의
  // 조/항 인용 괄호가 있는지만 봄.
  const leadingNum = before.match(/^\d{1,2}\)\s*/);
  const afterLeadingNum = leadingNum ? before.slice(leadingNum[0].length) : before;
  if (!/[)）]/.test(afterLeadingNum)) return null; // 조/항 인용 괄호가 없으면 라벨 아님
  const label = before.replace(/\s+$/, "");
  const body = trimmed.slice(quoteIdx);
  if (!label || !body) return null;
  return [label, body];
}

// 2026-08-20: splitIntoBlocks가 BRACKET_LABEL_WITH_TRAILING_RE(위, HEADING_LABEL_PATTERNS
// 앞에 선언)에 매칭되는 줄 "전체"(라벨+내용)를 통째로 heading(볼드)으로 만들어버려서,
// 내용이 한 문장으로 다음 줄까지 이어지면 첫 줄만 볼드, 이어지는 줄(다음 줄)은 안
// 볼드인 채로 뒤섞여 보이는 문제를 실제 스크린샷(한국자산관리공사 2021,
// 9ddc6393057cc532 — "[관련자 의견] 관련자는 감사 결과에 이견을 제기하지 않았고,
// 모범을 / 보여야 할 관리자의 위치에도...")으로 확인함(사용자 제보 — "1.은 작은
// 글씨인데 2.는 볼드체" 류와 같은 계열의 "글씨 크기 뒤죽박죽" 문제).
/** 위 라벨 패턴에 매칭되고 "]" 뒤에 실제 내용이 남아있으면 [라벨, 내용]으로 나눔
 * (splitLawCitationHeading과 같은 목적·같은 방식) — 라벨 하나로 줄이 끝나면(내용
 * 없음) null 반환(그 경우는 이미 위 "줄 전체가 라벨뿐" 패턴이 먼저 걸러서 실제로는
 * 거의 안 옴). */
function splitBracketLabelHeading(trimmed) {
  const m = BRACKET_LABEL_WITH_TRAILING_RE.exec(trimmed);
  if (!m) return null;
  const label = m[0].trim();
  const body = trimmed.slice(m[0].length).trim();
  if (!label || !body) return null;
  return [label, body];
}

/** ATTACHMENT_LABEL_RE에 매칭되면 [라벨, 나머지내용]으로 나눔(내용이 없으면 body를
 * 빈 문자열로 반환 — "붙임" 혼자 나오고 다음 줄부터 목록이 시작하는 문서도 있을 수
 * 있어서 splitLawCitationHeading/splitBracketLabelHeading과 달리 null을 반환 안 함). */
function splitAttachmentLabel(trimmed) {
  const m = ATTACHMENT_LABEL_RE.exec(trimmed);
  if (!m) return null;
  const label = m[1];
  const body = trimmed.slice(m[0].length).trim();
  return [label, body];
}

// 2026-08-19: 상위 개요 항목이 "1. 제목 / 2. 관계기관 / 3. ..."처럼 번호로 나열되는
// 문서인데, 제목 줄 맨 앞의 "1. "만 DB 적재 시점부터 유실된 경우가 실제로 있음(Colab
// 규모조사 — scripts/audit_title_number_and_wordbreak.py, 67,751건 전수 스캔 결과
// 4,330건/6.39%, 한국보훈복지의료공단·한국자산관리공사·한국토지주택공사 3개 기관에
// 96% 집중). raw_text 자체를 고치는 건 DB 백필이 필요해서 이번엔 화면 표시만 보정 —
// 조사 스크립트와 같은 조건(제목 줄엔 번호가 없는데 바로 다음 헤딩은 "2."(이상)로
// 시작)일 때만 "1. "을 붙여서 보여줌. TITLE_BLOCK_LEADING_NUM_RE는 fixMissingTitleNumber
// 에서 이미 번호가 붙어있는 제목 줄을 건드리지 않기 위한 가드로도 씀.
const TITLE_BLOCK_LEADING_NUM_RE = /^(\d{1,2})[.)]\s/;

/** splitIntoBlocks가 만든 heading 블록 중 제목(TITLE_RE로 판별, isTitle 플래그)
 * 블록 바로 다음이 "2."(이상) 번호로 시작하는 헤딩이면, 제목 줄 앞의 "1. "이 유실된
 * 것으로 보고 화면 표시용 텍스트에만 "1. "을 보정해 붙임. DB(원문)는 그대로 두고
 * isTitle 플래그(블록 생성 시 이미 계산해둠)도 그대로 유지되므로 스타일/목차 제외
 * 동작에는 영향 없음. */
function fixMissingTitleNumber(blocks) {
  const titleIdx = blocks.findIndex((b) => b.type === "heading" && b.isTitle);
  if (titleIdx === -1 || titleIdx === blocks.length - 1) return;
  const titleBlock = blocks[titleIdx];
  if (TITLE_BLOCK_LEADING_NUM_RE.test(titleBlock.text)) return; // 이미 번호 있음
  const next = blocks[titleIdx + 1];
  if (next.type !== "heading") return;
  const m = TITLE_BLOCK_LEADING_NUM_RE.exec(next.text);
  if (m && Number(m[1]) >= 2) {
    titleBlock.text = `1. ${titleBlock.text}`;
  }
}

