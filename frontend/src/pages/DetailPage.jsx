const TABLE_INTERLEAVE_RE = /연번[\s\n]*지적사항[\s\n]*처분/;

// 2026-08-20: classifyLine의 "가/나/다" 및 "1. 2. 3." 번호 헤딩 휴리스틱을 별도
// 함수로 뽑아냄 — splitIntoBlocks에서 각주 문단 흡수 여부를 판단할 때도 "이 줄이
// heading으로 분류된 이유가 이 번호 휴리스틱 때문인지"를 다시 물어야 해서
